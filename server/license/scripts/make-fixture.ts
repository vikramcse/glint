// Regenerates the cross-language token fixture shared by the Worker tests (vitest) and the
// app's tests (Tests/GlintLicensingTests). Run: npm run fixture
//
// The key in test/fixtures/test-private.key is a TEST key, published on purpose. It must
// never be used as LICENSE_PRIVATE_KEY in production.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { hashEmail, importSigningKeys, signToken } from "../src/tokens.ts";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const privateKey = readFileSync(join(root, "test/fixtures/test-private.key"), "utf8").trim();
const keys = await importSigningKeys(privateKey);
const existing = JSON.parse(readFileSync(join(root, "test/fixtures/tokens.json"), "utf8"));

const license = {
  licenseID: "9b3f6c1e-2a4d-4e8f-b7c6-5d4e3f2a1b0c",
  product: "glint-pro",
  majorVersion: 1,
  seats: 2,
  issuedAt: 1_791_600_000,
  emailHash: await hashEmail("Buyer@Example.com"),
  kind: "license" as const,
};
const installID = "6F1C2B3A-4D5E-4F60-8172-93A4B5C6D7E8";

const fixture = {
  note: "Generated by server/license/scripts/make-fixture.ts with a published TEST key. Not a production key.",
  publicKeyBase64: keys.publicKeyBase64,
  installID,
  workerLicenseKey: await signToken(license, keys),
  workerActivationToken: await signToken({ ...license, installID, kind: "activation", issuedAt: 1_791_600_100 }, keys),
  // Signed by the Swift `glint-license issue` tool with the same key; the Worker must accept it.
  swiftLicenseKey: existing.swiftLicenseKey,
};

const json = JSON.stringify(fixture, null, 2) + "\n";
writeFileSync(join(root, "test/fixtures/tokens.json"), json);
writeFileSync(join(root, "../../Tests/GlintLicensingTests/Fixtures/worker-tokens.json"), json);
console.log("Wrote test/fixtures/tokens.json and Tests/GlintLicensingTests/Fixtures/worker-tokens.json");
